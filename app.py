from flask import Flask, render_template, request
import joblib
import pandas as pd
import numpy as np
import json
import os
import shap

class NumpyEncoder(json.JSONEncoder):
    """Make numpy scalar types JSON-serializable."""
    def default(self, obj):
        if isinstance(obj, np.floating):
            return float(obj)
        if isinstance(obj, np.integer):
            return int(obj)
        return super().default(obj)

app = Flask(__name__)

# ── Model registry ────────────────────────────────────────────────────────────
MODEL_FILES = {
    "XGBoost":           "xgb_calories_model.joblib",
    "Random Forest":     "rf_calories_model.joblib",
    "Extra Trees":       "et_calories_model.joblib",
    "Gradient Boosting": "gb_calories_model.joblib",
    "Stacking":          "stack_calories_model.joblib",
}
MODEL_NAMES = list(MODEL_FILES.keys())

# Load all available models at startup
models = {}
for name, fname in MODEL_FILES.items():
    try:
        models[name] = joblib.load(fname)
        print(f"  ✅ Loaded: {name}")
    except Exception as e:
        print(f"  ⚠️  Could not load {name}: {e}")

# Load label encoders
try:
    label_encoders = joblib.load("label_encoders.joblib")
except Exception as e:
    print(f"Error loading label encoders: {e}")
    label_encoders = None

# Load model metrics (generated by train_all_models.py)
model_metrics = {}
best_model_name = "XGBoost"   # fallback
try:
    with open("model_metrics.json") as f:
        model_metrics = json.load(f)
    best_model_name = model_metrics.pop("best_model", "XGBoost")
    print(f"  🏆 Best model: {best_model_name}")
except Exception:
    print("  ℹ️  model_metrics.json not found — run train_all_models.py first.")

# ── Feature column order ──────────────────────────────────────────────────────
EXPECTED_COLUMNS = [
    "Age", "Gender", "Weight (kg)", "Height (m)", "Max_BPM", "Avg_BPM",
    "Resting_BPM", "Workout_Type", "Fat_Percentage", "Water_Intake (liters)",
    "Workout_Frequency (days/week)", "Experience_Level", "BMI", "Diet_Type",
    "Sleep_Duration (hours)", "Session_Duration (minutes)"
]

SHORT_NAMES = [
    "Age", "Gender", "Weight", "Height",
    "Max BPM", "Avg BPM", "Resting BPM", "Workout Type",
    "Fat %", "Water Intake", "Workout Freq",
    "Experience", "BMI", "Diet Type", "Sleep", "Session Dur."
]

NUMERIC_COLS_MAP = {
    "Age": "Age", "Weight (kg)": "Weight", "Height (m)": "Height",
    "Max_BPM": "Max BPM", "Avg_BPM": "Avg BPM", "Resting_BPM": "Resting BPM",
    "Fat_Percentage": "Fat %", "Water_Intake (liters)": "Water Intake",
    "Workout_Frequency (days/week)": "Workout Freq",
    "Experience_Level": "Experience", "BMI": "BMI",
    "Sleep_Duration (hours)": "Sleep", "Session_Duration (minutes)": "Session Dur."
}

# ── Route ─────────────────────────────────────────────────────────────────────
@app.route("/", methods=["GET", "POST"])
def index():
    form_data       = {}
    error           = None
    calories_burned = None
    feat_importance = None
    sensitivity     = None
    selected_model  = "XGBoost"
    selected_metrics= None
    shap_values_dict = None
    shap_expected_value = None

    if request.method == "POST":
        try:
            # ── Model selection ───────────────────────────────────────────
            selected_model = request.form.get("model_name", "XGBoost")
            if selected_model not in MODEL_NAMES:
                selected_model = "XGBoost"

            active_model = models.get(selected_model)
            if active_model is None:
                raise ValueError(f"Model '{selected_model}' is not loaded yet. "
                                 "Please run train_all_models.py first.")

            # ── Extract and validate form data ────────────────────────────
            form_data["age"] = int(request.form["age"])
            if form_data["age"] <= 0 or form_data["age"] > 120:
                raise ValueError("Age must be between 1 and 120.")

            form_data["gender"] = request.form["gender"]
            if form_data["gender"] not in ["Male", "Female"]:
                raise ValueError("Invalid gender selection.")

            form_data["weight"] = float(request.form["weight"])
            if form_data["weight"] <= 0 or form_data["weight"] > 300:
                raise ValueError("Weight must be between 0 and 300 kg.")

            form_data["height"] = float(request.form["height"])
            if form_data["height"] <= 0 or form_data["height"] > 3:
                raise ValueError("Height must be between 0 and 3 meters.")

            form_data["max_bpm"] = int(request.form["max_bpm"])
            if form_data["max_bpm"] < 100 or form_data["max_bpm"] > 240:
                raise ValueError("Max BPM must be between 100 and 240.")

            form_data["avg_bpm"] = int(request.form["avg_bpm"])
            if form_data["avg_bpm"] < 60 or form_data["avg_bpm"] > 200:
                raise ValueError("Avg BPM must be between 60 and 200.")

            form_data["resting_bpm"] = int(request.form["resting_bpm"])
            if form_data["resting_bpm"] < 30 or form_data["resting_bpm"] > 120:
                raise ValueError("Resting BPM must be between 30 and 120.")

            form_data["workout_type"] = request.form["workout_type"]
            if form_data["workout_type"] not in ["Yoga", "Cardio", "Strength", "HIIT"]:
                raise ValueError("Invalid workout type selection.")

            form_data["fat_percentage"] = float(request.form["fat_percentage"])
            if form_data["fat_percentage"] < 0 or form_data["fat_percentage"] > 50:
                raise ValueError("Fat percentage must be between 0 and 50.")

            form_data["water_intake"] = float(request.form["water_intake"])
            if form_data["water_intake"] < 0 or form_data["water_intake"] > 10:
                raise ValueError("Water intake must be between 0 and 10 liters.")

            form_data["workout_frequency"] = int(request.form["workout_frequency"])
            if form_data["workout_frequency"] < 1 or form_data["workout_frequency"] > 7:
                raise ValueError("Workout frequency must be between 1 and 7 days/week.")

            form_data["experience_level"] = int(request.form["experience_level"])
            if form_data["experience_level"] < 1 or form_data["experience_level"] > 3:
                raise ValueError("Invalid experience level selection.")

            form_data["bmi"] = round(float(request.form["bmi"]), 2)
            if form_data["bmi"] < 10 or form_data["bmi"] > 50:
                raise ValueError("BMI must be between 10 and 50.")

            form_data["diet_type"] = request.form["diet_type"]
            valid_diet_types = [
                "High Protein", "Paleo", "Keto", "Mediterranean", "Intermittent Fasting",
                "Balanced", "Vegan", "Low Carb", "Gluten-Free", "Vegetarian", "Low Fat"
            ]
            if form_data["diet_type"] not in valid_diet_types:
                raise ValueError("Invalid diet type selection.")

            form_data["sleep_duration"] = int(request.form["sleep_duration"])
            if form_data["sleep_duration"] < 0 or form_data["sleep_duration"] > 24:
                raise ValueError("Sleep duration must be between 0 and 24 hours.")

            form_data["session_duration"] = float(request.form["session_duration"])
            if form_data["session_duration"] <= 0 or form_data["session_duration"] > 600:
                raise ValueError("Session duration must be between 0 and 600 minutes.")

            # ── Build input DataFrame ─────────────────────────────────────
            input_data = {
                "Age": form_data["age"],
                "Gender": form_data["gender"],
                "Weight (kg)": form_data["weight"],
                "Height (m)": form_data["height"],
                "Max_BPM": form_data["max_bpm"],
                "Avg_BPM": form_data["avg_bpm"],
                "Resting_BPM": form_data["resting_bpm"],
                "Workout_Type": form_data["workout_type"],
                "Fat_Percentage": form_data["fat_percentage"],
                "Water_Intake (liters)": form_data["water_intake"],
                "Workout_Frequency (days/week)": form_data["workout_frequency"],
                "Experience_Level": form_data["experience_level"],
                "BMI": form_data["bmi"],
                "Diet_Type": form_data["diet_type"],
                "Sleep_Duration (hours)": form_data["sleep_duration"],
                "Session_Duration (minutes)": form_data["session_duration"]
            }
            input_df = pd.DataFrame([input_data])
            for col in ["Gender", "Workout_Type", "Diet_Type"]:
                input_df[col] = label_encoders[col].transform(input_df[col])
            input_df = input_df[EXPECTED_COLUMNS]

            # ── Predict ───────────────────────────────────────────────────
            calories_burned = round(float(active_model.predict(input_df)[0]), 1)

            # ── Selected model's metrics ──────────────────────────────────
            selected_metrics = model_metrics.get(selected_model)

            # ── Feature importance (only for tree models with the attribute) ──
            try:
                raw_imp = [float(x) * 100 for x in active_model.feature_importances_]
                feat_importance = dict(zip(SHORT_NAMES, [round(v, 2) for v in raw_imp]))
            except AttributeError:
                feat_importance = None   # Stacking / Ridge meta has no feature_importances_

            # ── SHAP Explanations (per-prediction feature attribution) ────
            shap_values_dict = None
            shap_expected_value = None
            try:
                if selected_model == "XGBoost":
                    import xgboost as xgb
                    dmat = xgb.DMatrix(input_df)
                    contribs = active_model.get_booster().predict(dmat, pred_contribs=True)
                    shap_vals = contribs[0, :-1]
                    ev = contribs[0, -1]
                    shap_values_dict = dict(zip(SHORT_NAMES, [round(float(v), 2) for v in shap_vals]))
                    shap_expected_value = round(float(ev), 2)
                elif selected_model != "Stacking":
                    explainer = shap.TreeExplainer(active_model)
                    shap_vals = explainer.shap_values(input_df)
                    
                    if isinstance(shap_vals, list):
                        sv = shap_vals[0][0]
                    elif len(shap_vals.shape) == 3:
                        sv = shap_vals[0, :, 0]
                    else:
                        sv = shap_vals[0]
                        
                    shap_values_dict = dict(zip(SHORT_NAMES, [round(float(v), 2) for v in sv]))
                    
                    ev = explainer.expected_value
                    if isinstance(ev, (list, np.ndarray)):
                        ev = ev[0]
                    shap_expected_value = round(float(ev), 2)
            except Exception as e:
                print(f"SHAP Error: {e}")

            # ── Sensitivity analysis (±10% per numeric feature) ───────────
            sensitivity = {}
            for col, label in NUMERIC_COLS_MAP.items():
                try:
                    orig  = float(input_df[col].iloc[0])
                    delta = max(abs(orig) * 0.1, 0.5)
                    df_up, df_dn = input_df.copy(), input_df.copy()
                    df_up[col] = orig + delta
                    df_dn[col] = orig - delta
                    sensitivity[label] = {
                        "up":   round(float(active_model.predict(df_up)[0]) - calories_burned, 1),
                        "down": round(float(active_model.predict(df_dn)[0]) - calories_burned, 1),
                    }
                except Exception:
                    sensitivity[label] = {"up": 0, "down": 0}

        except ValueError as e:
            error = str(e)
        except Exception as e:
            error = f"An unexpected error occurred: {str(e)}"

    return render_template(
        "index.html",
        form_data        = form_data,
        error            = error,
        calories_burned  = calories_burned,
        selected_model   = selected_model,
        model_names      = MODEL_NAMES,
        best_model_name  = best_model_name,
        model_metrics    = model_metrics,          # full dict for all models
        selected_metrics = selected_metrics,
        feat_importance  = json.dumps(feat_importance, cls=NumpyEncoder) if feat_importance else 'null',
        sensitivity      = json.dumps(sensitivity,     cls=NumpyEncoder) if sensitivity     else 'null',
        shap_values      = json.dumps(shap_values_dict, cls=NumpyEncoder) if shap_values_dict else 'null',
        shap_expected    = json.dumps(shap_expected_value, cls=NumpyEncoder) if shap_expected_value is not None else 'null',
        models_available = list(models.keys()),
    )

if __name__ == "__main__":
    app.run(debug=True)
